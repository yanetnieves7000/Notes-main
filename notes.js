// 1. Declare two numbers
const num1 = 15;
const num2 = 4;

// 2. Calculate and log operations
console.log("Addition:", num1 + num2); // 19
console.log("Subtraction:", num1 - num2); // 11
console.log("Multiplication:", num1 * num2); // 60
console.log("Division:", num1 / num2); // 3.75
console.log("Modulus:", num1 % num2); // 3

// 3. Calculate and log the square of the first number
const square = num1 ** 2;
console.log("Square of", num1, "is", square); // 225

// 4. Calculate and log the square root of the second number
const squareRoot = Math.sqrt(num2);
console.log("Square root of", num2, "is", squareRoot); // 2

// 5. Calculate and log the power of the first number raised to the second number
const power = Math.pow(num1, num2);
console.log(num1, "raised to the power of", num2, "is", power);